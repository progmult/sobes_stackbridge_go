-- Запрет пересекающихся подписок на один сервис у одного пользователя.
--
-- Уникальный индекс здесь не годится: он ловит только совпадение дат начала,
-- а перекрытие «январь без конца» и «май» пропустил бы. Нужен EXCLUDE, а он
-- работает поверх gist, который для скалярных типов доступен только с
-- btree_gist.
CREATE EXTENSION IF NOT EXISTS btree_gist;

-- daterange со скобками '[]' включает оба конца: подписка действует по месяц
-- окончания включительно. NULL в end_date даёт диапазон, не ограниченный
-- сверху, — ровно семантика бессрочной подписки.
--
-- Название сравнивается через lower(), как и в фильтрах выборки: «Yandex Plus»
-- и «yandex plus» — один сервис.
--
-- Миграция не выполнится, если пересечения уже накоплены. Это намеренно:
-- молча склеивать или удалять чужие записи хуже, чем остановить старт и
-- показать, что данные противоречат новому правилу.
ALTER TABLE subscriptions
    ADD CONSTRAINT subscriptions_no_overlap
    EXCLUDE USING gist (
        user_id WITH =,
        lower(service_name) WITH =,
        daterange(start_date, end_date, '[]') WITH &&
    );
